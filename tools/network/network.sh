#!/usr/bin/env bash
# ============================================================
# netool懒人工具箱 - 网络信息查看与连通性测试
# ============================================================
# 项目名称: netool懒人工具箱 (netool)
# 脚本名称: network.sh
# 脚本版本: 2.0
# 项目地址: https://gitee.com/suser747/netool
#
# 功能说明:
#   提供网络信息查看(IP 地址、路由、监听端口)与连通性测试
#   (Ping、DNS 解析)。支持命令行参数与交互式菜单两种使用方式,
#   仅做低风险查看与连通性测试,不修改任何系统配置。
#
# 使用方式:
#   network            直接执行进入交互菜单
#   network ip         查看 IP 地址
#   network ping 8.8.8.8   对指定主机执行 Ping 测试
#   network dns example.com  对指定域名执行 DNS 解析
#   network -h         显示帮助
#
# 退出码:
#   0 - 成功
#   1 - 一般错误
#   2 - 用法错误
#   3 - 权限错误
#   4 - 依赖缺失
# ============================================================

set -Eeuo pipefail

SCRIPT_NAME="network-tools"
SCRIPT_VERSION="2.0"

# 颜色控制变量: 仅在终端输出时启用颜色,被父工具箱调用时强制关闭颜色
COLOR_RED=""
COLOR_GREEN=""
COLOR_YELLOW=""
COLOR_BLUE=""
COLOR_CYAN=""
COLOR_BOLD=""
COLOR_RESET=""

# 标准输出连接到终端时初始化 ANSI 颜色转义码
if [[ -t 1 ]]; then
  COLOR_RED=$'\033[31m'
  COLOR_GREEN=$'\033[32m'
  COLOR_YELLOW=$'\033[33m'
  COLOR_BLUE=$'\033[34m'
  COLOR_CYAN=$'\033[36m'
  COLOR_BOLD=$'\033[1m'
  COLOR_RESET=$'\033[0m'
fi

# 作为子模块被父工具箱调用时关闭颜色,避免日志格式混乱
if [[ -n "${AYU_TOOLBOX:-}" ]]; then
  COLOR_RED=""
  COLOR_GREEN=""
  COLOR_YELLOW=""
  COLOR_BLUE=""
  COLOR_CYAN=""
  COLOR_BOLD=""
  COLOR_RESET=""
fi

# ------------------------------------------------------------------------------
# 函数: log_info
# 功能: 输出信息级别日志,带颜色与级别前缀
# 参数: $* - 要输出的消息内容
# 返回值: 0 - 成功
# ------------------------------------------------------------------------------
log_info() { printf "%s%s[信息]%s %s\n" "$COLOR_BOLD" "$COLOR_CYAN" "$COLOR_RESET" "$*"; }

# ------------------------------------------------------------------------------
# 函数: log_success
# 功能: 输出成功级别日志,带颜色与级别前缀
# 参数: $* - 要输出的消息内容
# 返回值: 0 - 成功
# ------------------------------------------------------------------------------
log_success() { printf "%s%s[完成]%s %s\n" "$COLOR_BOLD" "$COLOR_GREEN" "$COLOR_RESET" "$*"; }

# ------------------------------------------------------------------------------
# 函数: log_warn
# 功能: 输出警告级别日志,带颜色与级别前缀
# 参数: $* - 要输出的消息内容
# 返回值: 0 - 成功
# ------------------------------------------------------------------------------
log_warn() { printf "%s%s[警告]%s %s\n" "$COLOR_BOLD" "$COLOR_YELLOW" "$COLOR_RESET" "$*"; }

# ------------------------------------------------------------------------------
# 函数: log_error
# 功能: 输出错误级别日志到 stderr,带颜色与级别前缀
# 参数: $* - 要输出的消息内容
# 返回值: 0 - 成功
# ------------------------------------------------------------------------------
log_error() { printf "%s%s[错误]%s %s\n" "$COLOR_BOLD" "$COLOR_RED" "$COLOR_RESET" "$*" >&2; }

# ------------------------------------------------------------------------------
# 函数: die
# 功能: 输出错误消息后立即退出
# 参数: $* - 错误消息
# 返回值: 1 - 始终以退出码 1 退出
# ------------------------------------------------------------------------------
die() { log_error "$*"; exit 1; }

# ------------------------------------------------------------------------------
# 函数: on_error
# 功能: ERR 信号回调,在 set -e 触发退出前打印出错行号与退出码
# 参数: 无(由 trap 自动注入)
# 返回值: 以原退出码退出
# ------------------------------------------------------------------------------
on_error() {
  local exit_code=$?
  log_error "脚本在第 ${BASH_LINENO[0]:-unknown} 行附近执行失败,退出码:${exit_code}"
  exit "$exit_code"
}

trap on_error ERR

# ------------------------------------------------------------------------------
# 函数: read_prompt
# 功能: 读取用户输入到指定变量,兼容管道与无 TTY 环境
# 参数: $1 - 提示文本, $2 - 用于存放输入的变量名
# 返回值: 0 - 读取成功, 1 - EOF 或读取失败
# ------------------------------------------------------------------------------
read_prompt() {
  local prompt="$1"
  local var_name="$2"
  local value=""

  if [[ ! -t 0 && -t 1 && -r /dev/tty ]]; then
    if { printf "%s" "$prompt" >/dev/tty && IFS= read -r value </dev/tty; } 2>/dev/null; then
      printf -v "$var_name" "%s" "$value"
      return 0
    fi
  fi

  printf "%s" "$prompt"
  IFS= read -r value || [[ -n "$value" ]] || return 1
  printf -v "$var_name" "%s" "$value"
}

# ------------------------------------------------------------------------------
# 函数: command_exists
# 功能: 检查指定命令是否在 PATH 中可用
# 参数: $1 - 命令名
# 返回值: 0 - 存在, 非 0 - 不存在
# ------------------------------------------------------------------------------
command_exists() {
  command -v "$1" >/dev/null 2>&1
}

# ------------------------------------------------------------------------------
# 函数: check_ip_command
# 功能: 检测 ip 命令是否可用,不可用时给出降级使用 ifconfig/route 的提示
# 参数: 无
# 返回值: 0 - 始终成功(仅提示,不阻断执行)
# ------------------------------------------------------------------------------
check_ip_command() {
  if ! command_exists ip; then
    log_warn "未检测到 ip 命令,将降级使用 ifconfig/route(信息可能不全)。"
  fi
}

# ------------------------------------------------------------------------------
# 函数: usage
# 功能: 输出脚本帮助信息
# 参数: 无
# 返回值: 0 - 始终成功
# ------------------------------------------------------------------------------
usage() {
  cat <<EOF
netool懒人工具箱 | 网络工具 v${SCRIPT_VERSION}

用法:
  network [操作] [参数]

操作:
  info            查看网络信息(默认)
  ip              查看 IP 地址
  route           查看路由
  ports           查看监听端口
  ping [host]     Ping 连通性测试,默认 223.5.5.5
  dns [domain]    DNS 解析测试,默认 example.com

说明:
  当前模块只做低风险查看和连通性测试。
EOF
}

# ------------------------------------------------------------------------------
# 函数: print_banner
# 功能: 打印脚本横幅; 作为子模块被调用时静默跳过
# 参数: 无
# 返回值: 0 - 始终成功
# ------------------------------------------------------------------------------
print_banner() {
  if [[ -n "${AYU_TOOLBOX:-}" ]]; then return 0; fi
  printf "%s\n" "------------------------------------------------------------"
  printf "netool懒人工具箱 | 网络工具 v%s\n" "$SCRIPT_VERSION"
  printf "%s\n" "------------------------------------------------------------"
}

# ------------------------------------------------------------------------------
# 函数: do_ip
# 功能: 显示本机 IP 地址与公网 IP 地址
# 参数: 无
# 返回值: 0 - 始终成功(查询失败时输出提示但不报错)
# ------------------------------------------------------------------------------
do_ip() {
  printf "\nIP 地址:\n"
  if command_exists ip; then
    ip -brief addr 2>/dev/null | sed 's/^/  /'
  else
    ifconfig 2>/dev/null | sed 's/^/  /' || true
  fi
  printf "\n公网 IP:\n"
  if command_exists curl; then
    curl -fsSL --connect-timeout 5 https://api.ipify.org 2>/dev/null | sed 's/^/  /' || printf "  查询失败\n"
    printf "\n"
  else
    printf "  缺少 curl\n"
  fi
}

# ------------------------------------------------------------------------------
# 函数: do_route
# 功能: 显示系统路由表
# 参数: 无
# 返回值: 0 - 始终成功
# ------------------------------------------------------------------------------
do_route() {
  printf "\n路由:\n"
  if command_exists ip; then
    ip route 2>/dev/null | sed 's/^/  /'
  else
    route -n 2>/dev/null | sed 's/^/  /' || true
  fi
}

# ------------------------------------------------------------------------------
# 函数: do_ports
# 功能: 显示系统监听端口列表,优先使用 ss,回退 netstat
# 参数: 无
# 返回值: 0 - 始终成功(命令缺失或失败时输出警告)
# ------------------------------------------------------------------------------
do_ports() {
  printf "\n监听端口:\n"
  if command_exists ss; then
    ss -tulpen 2>/dev/null | sed -n '1,60p' || log_warn "ss 执行失败,无法列出监听端口。"
  elif command_exists netstat; then
    netstat -tulpen 2>/dev/null | sed -n '1,60p' || log_warn "netstat 执行失败,无法列出监听端口。"
  else
    log_warn "缺少 ss 或 netstat,无法列出监听端口。"
  fi
}

# ------------------------------------------------------------------------------
# 函数: do_ping
# 功能: 对指定主机执行 4 次 Ping 连通性测试
# 参数: $1 - 目标主机地址(可选,默认 223.5.5.5)
# 返回值: 0 - 成功, 非 0 - ping 命令返回非零退出码
# ------------------------------------------------------------------------------
do_ping() {
  local host="${1:-223.5.5.5}"
  printf "\nPing: %s\n" "$host"
  ping -c 4 "$host"
}

# ------------------------------------------------------------------------------
# 函数: do_dns
# 功能: 对指定域名执行 DNS 解析,按 dig > nslookup > getent 顺序回退
# 参数: $1 - 待解析域名(可选,默认 example.com)
# 返回值: 0 - 成功, 1 - 缺少所有解析工具
# ------------------------------------------------------------------------------
do_dns() {
  local domain="${1:-example.com}"
  printf "\nDNS: %s\n" "$domain"
  if command_exists dig; then
    dig +short "$domain"
  elif command_exists nslookup; then
    nslookup "$domain"
  elif command_exists getent; then
    getent hosts "$domain"
  else
    die "缺少 dig/nslookup/getent"
  fi
}

# ------------------------------------------------------------------------------
# 函数: do_info
# 功能: 依次输出 IP 地址、路由、监听端口等综合网络信息
# 参数: 无
# 返回值: 0 - 始终成功
# ------------------------------------------------------------------------------
do_info() {
  do_ip
  do_route
  do_ports
}

# ------------------------------------------------------------------------------
# 函数: run_action
# 功能: 根据传入的操作名分发到对应处理函数
# 参数: $1 - 操作名, $2 - 操作参数
# 返回值: 0 - 成功, 1 - 未知操作
# ------------------------------------------------------------------------------
run_action() {
  local action="${1:-info}"
  shift || true
  case "$action" in
    info|status) do_info ;;
    ip|addr) do_ip ;;
    route|gateway) do_route ;;
    ports|port|listen) do_ports ;;
    ping) do_ping "${1:-223.5.5.5}" ;;
    dns|resolve) do_dns "${1:-example.com}" ;;
    -h|--help) usage ;;
    --version) printf "%s\n" "$SCRIPT_VERSION" ;;
    *) die "未知操作:$action" ;;
  esac
}

# ------------------------------------------------------------------------------
# 函数: interactive_loop
# 功能: 交互式菜单循环,等待用户选择网络操作直至返回
# 参数: 无
# 返回值: 0 - 用户选择返回, 1 - 无法读取输入
# ------------------------------------------------------------------------------
interactive_loop() {
  local answer=""
  while true; do
    printf "\n请选择网络操作:\n"
    printf "  1. 查看网络信息\n"
    printf "  2. 查看 IP 地址\n"
    printf "  3. 查看路由\n"
    printf "  4. 查看监听端口\n"
    printf "  5. Ping 测试\n"
    printf "  6. DNS 解析测试\n"
    printf "  b. 返回\n"
    if ! read_prompt "输入编号: " answer; then
      log_error "无法读取输入。"
      return 1
    fi

    case "$answer" in
      1) do_info ;;
      2) do_ip ;;
      3) do_route ;;
      4) do_ports ;;
      5) do_ping ;;
      6) do_dns ;;
      b|B|back|返回) return 0 ;;
      "") log_warn "未读取到输入,请重新输入。" ;;
      *) log_warn "无效输入,请输入 1-6 或 b 返回。" ;;
    esac
  done
}

# ------------------------------------------------------------------------------
# 函数: main
# 功能: 脚本入口,打印横幅后根据是否带参数选择命令行模式或交互模式
# 参数: $@ - 全部命令行参数
# 返回值: 0 - 成功, 非 0 - 子函数错误码
# ------------------------------------------------------------------------------
main() {
  print_banner
  check_ip_command
  if (($# > 0)); then
    run_action "$@"
  else
    interactive_loop
  fi
}

main "$@"
